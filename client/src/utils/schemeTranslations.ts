export function getSchemeLocalizedName(schemeId: string, lang: SupportedLanguage): string | undefined {
  if (lang === 'en') return undefined;
  return SCHEME_TRANSLATIONS[schemeId]?.[lang]?.name;
}

export function getSchemeLocalizedSummary(scheme: Scheme, lang: SupportedLanguage): string {
  if (lang === 'hi') {
    return scheme.hindiSummary || scheme.summary;
  }
  if (lang === 'en') {
    return scheme.summary;
  }
  const localized = SCHEME_TRANSLATIONS[scheme.id]?.[lang]?.summary;
  return localized || scheme.summary;
}

export function getSchemeNarrationText(
  scheme: Scheme,
  matchResult: { estimatedSubsidyAmount: number; estimatedLoanAmount: number },
  lang: SupportedLanguage
): string {
  const { estimatedSubsidyAmount, estimatedLoanAmount } = matchResult;
  const subsidyNum = estimatedSubsidyAmount.toLocaleString('en-IN');
  const loanNum = estimatedLoanAmount.toLocaleString('en-IN');
  const rate = scheme.interestRatePerAnnum;

  switch (lang) {
    case 'hi': {
      const name = scheme.hindiName || scheme.name;
      const summary = scheme.hindiSummary || scheme.summary;
      const sub = estimatedSubsidyAmount > 0 ? `${subsidyNum} रुपये` : 'शून्य रुपये';
      const loan = estimatedLoanAmount > 0 ? `${loanNum} रुपये` : 'शून्य रुपये';
      return `${name}। ${summary}। अनुमानित पूंजी सब्सिडी: ${sub}। आवश्यक बैंक ऋण: ${loan}। रियायती ब्याज दर: ${rate}।`;
    }

    case 'te': {
      const localized = SCHEME_TRANSLATIONS[scheme.id]?.te;
      const name = localized?.name || scheme.name;
      const summary = localized?.summary || scheme.summary;
      const sub = estimatedSubsidyAmount > 0 ? `${subsidyNum} రూపాయలు` : 'సున్నా రూపాయలు';
      const loan = estimatedLoanAmount > 0 ? `${loanNum} రూపాయలు` : 'సున్నా రూపాయలు';
      return `${name}. ${summary}. అర్హత కలిగిన మూలధన సబ్సిడీ: ${sub}. అవసరమైన బ్యాంకు రుణం: ${loan}. రాయితీ వడ్డీ రేటు: ${rate}.`;
    }

    case 'mr': {
      const localized = SCHEME_TRANSLATIONS[scheme.id]?.mr;
      const name = localized?.name || scheme.hindiName || scheme.name;
      const summary = localized?.summary || scheme.hindiSummary || scheme.summary;
      const sub = estimatedSubsidyAmount > 0 ? `${subsidyNum} रुपये` : 'शून्य रुपये';
      const loan = estimatedLoanAmount > 0 ? `${loanNum} रुपये` : 'शून्य रुपये';
      return `${name}. ${summary}. अंदाजित भांडवली अनुदान: ${sub}. आवश्यक बँक कर्ज: ${loan}. सवलतीचा व्याजदर: ${rate}.`;
    }

    case 'bn': {
      const localized = SCHEME_TRANSLATIONS[scheme.id]?.bn;
      const name = localized?.name || scheme.name;
      const summary = localized?.summary || scheme.summary;
      const sub = estimatedSubsidyAmount > 0 ? `${subsidyNum} টাকা` : 'শূন্য টাকা';
      const loan = estimatedLoanAmount > 0 ? `${loanNum} টাকা` : 'শূন্য টাকা';
      return `${name}। ${summary}। আনুমানিক মূলধন ভর্তুকি: ${sub}। প্রয়োজনীয় ব্যাংক ঋণ: ${loan}। সুদের হার: ${rate}।`;
    }

    case 'pa': {
      const localized = SCHEME_TRANSLATIONS[scheme.id]?.pa;
      const name = localized?.name || scheme.name;
      const summary = localized?.summary || scheme.summary;
      const sub = estimatedSubsidyAmount > 0 ? `${subsidyNum} ਰੁਪਏ` : 'ਸਿਫ਼ਰ ਰੁਪਏ';
      const loan = estimatedLoanAmount > 0 ? `${loanNum} ਰੁਪਏ` : 'ਸਿਫ਼ਰ ਰੁਪਏ';
      return `${name} ਸਕੀਮ. ${summary}. ਅਨੁਮਾਨਿਤ ਪੂੰਜੀ ਸਬਸਿਡੀ: ${sub}. ਲੋੜੀਂਦਾ ਬੈਂਕ ਕਰਜ਼ਾ: ${loan}. ਰਿਆਇਤੀ ਵਿਆਜ ਦਰ: ${rate}.`;
    }

    default: {
      const sub = `Rupees ${subsidyNum}`;
      const loan = `Rupees ${loanNum}`;
      return `${scheme.name}. ${scheme.summary}. Eligible Capital Subsidy: ${sub}. Estimated loan: ${loan}. Concessional interest rate: ${rate}.`;
    }
  }
}

